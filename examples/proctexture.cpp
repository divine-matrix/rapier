#include "sabre/core/core.h"
#include "sabre/core/texture.h"
#include "sabre/tools/debug.h"
#include <GL/glew.h>
#include <SDL3/SDL.h>
#include <cstdint>
#include <iostream>

int main() {
  sabre::core::sabre_GlobalContext gctx;
  gctx.defaultFilterMode = sabre::core::sabre_TextureFilterMode::NEAREST;
  gctx.sdl_flags = SDL_INIT_VIDEO;
  gctx.project_dir = "/Users/blockgenie/Documents/_divinematrix/rapier/";

  if (!sabre::core::sabre_Init(gctx)) {
    std::cerr << "sabre_Init failed: " << SDL_GetError() << "\n";
    return 1;
  }

  // FIX: Use OpenGL 3.2 Core Profile (macOS does not support 3.2+ compatibility
  // profile)
  SDL_GL_SetAttribute(SDL_GL_CONTEXT_MAJOR_VERSION, 3);
  SDL_GL_SetAttribute(SDL_GL_CONTEXT_MINOR_VERSION, 2);
  SDL_GL_SetAttribute(SDL_GL_CONTEXT_PROFILE_MASK, SDL_GL_CONTEXT_PROFILE_CORE);
  // FIXED: In SDL3, forward compatibility is passed via SDL_GL_CONTEXT_FLAGS
  SDL_GL_SetAttribute(SDL_GL_CONTEXT_FLAGS,
                      SDL_GL_CONTEXT_FORWARD_COMPATIBLE_FLAG);
  SDL_GL_SetAttribute(SDL_GL_DOUBLEBUFFER, 1);

  SDL_Window *window =
      SDL_CreateWindow("Sabre Procedural Texture Demo", 960, 600,
                       SDL_WINDOW_OPENGL | SDL_WINDOW_RESIZABLE);
  if (!window) {
    std::cerr << "SDL_CreateWindow failed: " << SDL_GetError() << "\n";
    sabre::core::sabre_Quit();
    return 1;
  }

  SDL_GLContext glContext = SDL_GL_CreateContext(window);
  if (!glContext) {
    std::cerr << "SDL_GL_CreateContext failed: " << SDL_GetError() << "\n";
    SDL_DestroyWindow(window);
    sabre::core::sabre_Quit();
    return 1;
  }

  SDL_GL_MakeCurrent(window, glContext);
  SDL_GL_SetSwapInterval(1);

  // Required before glewInit() on macOS OpenGL contexts to expose Core Profile
  // entry points
  glewExperimental = GL_TRUE;
  const GLenum glewStatus = glewInit();
  if (glewStatus != GLEW_OK) {
    std::cerr << "glewInit failed: " << glewGetErrorString(glewStatus) << "\n";
    SDL_GL_DestroyContext(glContext);
    SDL_DestroyWindow(window);
    sabre::core::sabre_Quit();
    return 1;
  }
  glGetError(); // Clear any benign GL error generated by glewInit
  IMGUI_CHECKVERSION();
  ImGui::CreateContext();
  ImGuiIO &ioRef = ImGui::GetIO();
  ioRef.ConfigFlags |= ImGuiConfigFlags_NavEnableKeyboard;

  ImGui_ImplSDL3_InitForOpenGL(window, static_cast<void *>(glContext));
  ImGui_ImplOpenGL3_Init("#version 150");
  auto procTex = sabre::core::sabre_CreateProcTextureObject(
      gctx, 64, 64, sabre::core::sabre_TextureFilterMode::NEAREST);
  procTex.renderRect = {120.0f, 90.0f, 320.0f, 320.0f};

  uint8_t framePhase = 0;
  bool isRunning = true;
  SDL_Event event{};

  sabre::tools::debug::sabre_PerfStats perfStats{};
  sabre::tools::debug::DebugDrawState drawState{};

  while (isRunning) {
    const uint64_t frameStartTicks = SDL_GetPerformanceCounter();

    // FIX: Forward SDL events to ImGui so UI interaction works
    while (SDL_PollEvent(&event)) {
      ImGui_ImplSDL3_ProcessEvent(&event);
      if (event.type == SDL_EVENT_QUIT) {
        isRunning = false;
      }
    }

    ImGui_ImplOpenGL3_NewFrame();
    ImGui_ImplSDL3_NewFrame();
    ImGui::NewFrame();

    const uint64_t genStartTicks = SDL_GetPerformanceCounter();
    if (drawState.animatePattern) {
      for (uint32_t yCoord = 0; yCoord < procTex.height; ++yCoord) {
        for (uint32_t xCoord = 0; xCoord < procTex.width; ++xCoord) {
          const uint8_t redVal =
              static_cast<uint8_t>((xCoord ^ yCoord) + framePhase);
          const uint8_t greenVal =
              static_cast<uint8_t>(xCoord * 4 + framePhase);
          const uint8_t blueVal = static_cast<uint8_t>(yCoord * 4);
          sabre::core::setPixelColor(procTex, xCoord, yCoord, redVal, greenVal,
                                     blueVal, 255);
        }
      }
      ++framePhase;
    }
    const uint64_t genEndTicks = SDL_GetPerformanceCounter();

    glClearColor(0.10f, 0.12f, 0.16f, 1.0f);
    glClear(GL_COLOR_BUFFER_BIT);

    // FIX: Pass gctx so sabre_RenderProcTextureObject loads shaders via
    // sabre_LoadFile
    const uint64_t renderStartTicks = SDL_GetPerformanceCounter();
    sabre::core::sabre_RenderProcTextureObject(gctx, window, procTex);
    const uint64_t renderEndTicks = SDL_GetPerformanceCounter();

    // FIX: Build debug UI and submit ImGui draw data after procedural texture
    // draw
    const uint64_t imguiStartTicks = SDL_GetPerformanceCounter();
    sabre::tools::debug::draw(gctx, procTex, perfStats, drawState);
    ImGui::Render();
    ImGui_ImplOpenGL3_RenderDrawData(ImGui::GetDrawData());
    const uint64_t imguiEndTicks = SDL_GetPerformanceCounter();

    SDL_GL_SwapWindow(window);

    const uint64_t frameEndTicks = SDL_GetPerformanceCounter();

    // FIX: Smooth timings with an exponential moving average for readable debug
    // UI
    constexpr double kSmoothFactor = 0.15;
    perfStats.cpuGenMs =
        perfStats.cpuGenMs * (1.0 - kSmoothFactor) +
        sabre::tools::debug::ticksToMs(genStartTicks, genEndTicks) *
            kSmoothFactor;
    perfStats.renderTexMs =
        perfStats.renderTexMs * (1.0 - kSmoothFactor) +
        sabre::tools::debug::ticksToMs(renderStartTicks, renderEndTicks) *
            kSmoothFactor;
    perfStats.imguiMs =
        perfStats.imguiMs * (1.0 - kSmoothFactor) +
        sabre::tools::debug::ticksToMs(imguiStartTicks, imguiEndTicks) *
            kSmoothFactor;
    perfStats.frameMs =
        perfStats.frameMs * (1.0 - kSmoothFactor) +
        sabre::tools::debug::ticksToMs(frameStartTicks, frameEndTicks) *
            kSmoothFactor;
  }
  // FIX: Release cached VAO/VBO/shader before destroying the OpenGL context
  sabre::core::shutdownProcTextureRenderer();
  sabre::core::destroyProcTextureObject(procTex);

  ImGui_ImplOpenGL3_Shutdown();
  ImGui_ImplSDL3_Shutdown();
  ImGui::DestroyContext();

  SDL_GL_DestroyContext(glContext);
  SDL_DestroyWindow(window);
  sabre::core::sabre_Quit();
  return 0;
}
